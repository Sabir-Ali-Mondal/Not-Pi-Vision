    async executePrompt(promptText, aiEngine = 'gemini', buttonElement = null) {
        if (aiEngine === 'chatGPT') {
            const searchUrl = `https://chatgpt.com/?q=${encodeURIComponent(promptText)}`;
            window.open(searchUrl, '_blank', 'width=800,height=600');
            return { success: true, manual: true };
        } else if (aiEngine === 'gemini') {
            if (buttonElement) {
                buttonElement.disabled = true;
                buttonElement.innerHTML = 'Generating... <span class="spinner-border spinner-border-sm" role="status" aria-hidden="true"></span>';
            }

            try {
                const response = await fetch('/api/generate', {
                    method: 'POST',
                    headers: {
                        'Content-Type': 'application/json'
                    },
                    body: JSON.stringify({
                        prompt: promptText
                    })
                });

                const data = await response.json();
                
                if (buttonElement) {
                    buttonElement.disabled = false;
                    buttonElement.innerHTML = 'Generate <i class="bi bi-lightning-charge"></i>';
                }

                return { success: true, content: data.content, manual: false };
            } catch (error) {
                console.error('Error:', error);
                
                if (buttonElement) {
                    buttonElement.disabled = false;
                    buttonElement.innerHTML = 'Generate <i class="bi bi-lightning-charge"></i>';
                }

                return { success: false, error: error.message, manual: false };
            }
        }
    }
