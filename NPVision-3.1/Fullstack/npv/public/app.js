function openWorkspace(workspaceId) {
    const workspace = workspaces.find(w => w.id === workspaceId);
    if (workspace) {
        currentWorkspace = workspace;
        document.getElementById('dashboardScreen').classList.remove('active');
        document.getElementById('workspaceScreen').classList.add('active');
        document.getElementById('mobileWorkspaceTitle').textContent = workspace.name;
        
        // Initialize topics for this workspace
        if (!topics[workspaceId]) {
            topics[workspaceId] = [
                { id: 1, name: 'Introduction', status: 'ready' },
                { id: 2, name: 'Core Concepts', status: 'pending' },
                { id: 3, name: 'Advanced Topics', status: 'ready' }
            ];
        }
        renderTopics(workspaceId);
    }
}

