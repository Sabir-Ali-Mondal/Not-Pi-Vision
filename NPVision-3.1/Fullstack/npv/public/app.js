function showToast(message, type = 'info') {
    const toastContainer = document.getElementById('toastContainer');
    const toast = document.createElement('div');
    
    let iconClass = 'bi-info-circle';
    let borderColor = 'rgba(34, 197, 94, 0.4)';
    
    if (type === 'error') {
        iconClass = 'bi-exclamation-circle';
        borderColor = 'rgba(239, 68, 68, 0.4)';
    } else if (type === 'success') {
        iconClass = 'bi-check-circle';
    }
    
    toast.className = 'custom-toast ' + type;
    toast.innerHTML = `
        <i class="bi ${iconClass}"></i>
        <span>${message}</span>
    `;
    toastContainer.appendChild(toast);
    
    setTimeout(() => {
        toast.style.animation = 'slideInRight 0.3s ease reverse';
        setTimeout(() => toast.remove(), 300);
    }, 3000);
}

class TTSVoiceSelector {
    constructor() {
        this.voices = [];
        this.mainLangs = ['en-IN', 'hi-IN', 'bn-IN', 'bn_IN', 'hi_IN', 'en_IN'];
        this.selectedVoices = [];
        this.otherVoices = [];
        this.PAGE_SIZE = 25;
        this.currentPage = 0;
        this.init()
    }
    init() {
        const s = document.getElementById('loadingStatus'),
            l = () => {
                this.voices = speechSynthesis.getVoices();
                if (this.voices.length < 5 && !this.voicesLoadedTimeout) {
                    this.voicesLoadedTimeout = setTimeout(l, 500);
                    s.textContent = `Loading TTS Voices... (${this.voices.length} detected)`;
                    return
                }
                clearTimeout(this.voicesLoadedTimeout);
                s.style.display = 'none';
                document.getElementById('voiceSelectorUI').style.display = 'block';
                s.textContent = `Voices Loaded: ${this.voices.length} total.`;
                this.categorizeAndDisplayVoices()
            };
        speechSynthesis.onvoiceschanged = l;
        setTimeout(l, 100);
        document.getElementById('prevPage').addEventListener('click', () => this.changePage(-1));
        document.getElementById('nextPage').addEventListener('click', () => this.changePage(1))
    }
    categorizeAndDisplayVoices() {
        const m = document.getElementById('mainVoices');
        m.innerHTML = '';
        this.otherVoices = [];
        this.voices.forEach((v, i) => {
            v.originalIndex = i;
            if (this.mainLangs.includes(v.lang)) this.appendVoiceToList(m, v);
            else this.otherVoices.push(v)
        });
        this.otherVoices.sort((a, b) => {
            const p = v => {
                    const l = v.lang.toLowerCase();
                    if (l.startsWith('bn')) return 1;
                    if (l.startsWith('hi')) return 2;
                    if (l.startsWith('en')) return 3;
                    if (l.includes('-IN')) return 4;
                    return 5
                },
                d = p(a) - p(b);
            return d !== 0 ? d : a.lang.localeCompare(b.lang)
        });
        this.currentPage = 0;
        this.renderOtherVoices();
        this.selectDefaultVoice()
    }
    selectDefaultVoice() {
        const enVoices = this.voices.filter(v => v.lang.startsWith('en'));
        const priorities = ['en-IN', 'en_IN', 'en_US', 'en-US', 'en_UK', 'en-UK'];
        let d = null;
        for (let locale of priorities) {
            d = enVoices.find(v => v.lang === locale);
            if (d) break
        }
        if (!d) d = enVoices.find(v => v.lang.includes('-IN')) || enVoices.find(v => v.lang.includes('-GB')) || enVoices.find(v => v.lang.includes('-US')) || enVoices[0];
        if (d) {
            const c = document.querySelector(`input[type="checkbox"][value="${d.originalIndex}"]`);
            if (c) {
                c.checked = true;
                this.updateSelection()
            }
        }
    }
    appendVoiceToList(u, v) {
        const t = `${v.lang} | ${v.name}`,
            l = document.createElement('li'),
            c = document.createElement('input');
        c.type = 'checkbox';
        c.value = v.originalIndex;
        c.style.cursor = 'pointer';
        c.addEventListener('change', () => this.updateSelection());
        l.appendChild(c);
        l.appendChild(document.createTextNode(' ' + t));
        l.style.padding = '0.25rem';
        l.style.cursor = 'pointer';
        u.appendChild(l)
    }
    renderOtherVoices() {
        const o = document.getElementById('otherVoices'),
            p = document.getElementById('pageInfo'),
            pr = document.getElementById('prevPage'),
            n = document.getElementById('nextPage');
        o.innerHTML = '';
        const s = this.currentPage * this.PAGE_SIZE,
            e = s + this.PAGE_SIZE,
            vp = this.otherVoices.slice(s, e);
        vp.forEach(v => this.appendVoiceToList(o, v));
        const tp = Math.ceil(this.otherVoices.length / this.PAGE_SIZE);
        p.textContent = `Page ${this.currentPage+1} of ${tp||1}`;
        pr.disabled = this.currentPage === 0;
        n.disabled = this.currentPage >= tp - 1
    }
    changePage(d) {
        this.currentPage += d;
        this.renderOtherVoices()
    }
    updateSelection() {
        this.selectedVoices = [];
        const a = document.querySelectorAll('#mainVoices input[type=checkbox], #otherVoices input[type=checkbox]');
        a.forEach(c => {
            if (c.checked) {
                const i = parseInt(c.value);
                this.selectedVoices.push(this.voices[i])
            }
        });
        const t = document.getElementById('selectedDetails');
        if (this.selectedVoices.length < 1) t.value = '⚠️ Select at least one voice for narration.';
        else t.value = this.selectedVoices.map(v => `${v.lang} | ${v.name}`).join('\n')
    }
}

function toggleNotesSidebar() {
    const sidebar = document.getElementById('notesSidebar');
    sidebar.classList.toggle('collapsed');
}
