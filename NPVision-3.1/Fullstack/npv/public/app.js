function sendContextToTutor() {
  if (!currentWorkspace) {
    showToast('No workspace selected', 'error');
    return;
  }

  const moduleData = {
    description: vizContent || 'No visualization loaded',
    html: vizContent || 'No HTML visualization'
  };

  const tutorPrompt = buildTutorPrompt({
    topic: currentWorkspace.name,
    chapter: 'Current Chapter',
    unit: 'Current Unit',
    workspace: currentWorkspace.name,
    moduleData: moduleData
  });

  // Add to chat
  addChatMessage('system', tutorPrompt);
  generateWithGemini(tutorPrompt, false).then(response => {
    if (response) {
      addChatMessage('tutor', response);
    }
  });

  showToast('Context sent to tutor', 'success');
}

function addChatMessage(sender, message) {
  const chatMessages = document.getElementById('chatMessages');
  const messageDiv = document.createElement('div');
  messageDiv.className = `chat-message ${sender}`;
  messageDiv.innerHTML = `
    <div class="message-content">
      ${sender === 'tutor' ? '<i class="bi bi-robot"></i>' : '<i class="bi bi-person"></i>'}
      <p>${message}</p>
    </div>
  `;
  chatMessages.appendChild(messageDiv);
  chatMessages.scrollTop = chatMessages.scrollHeight;
}

async function sendMessage() {
  const input = document.getElementById('tutorInput');
  const message = input.value.trim();
  
  if (!message) return;
  
  addChatMessage('user', message);
  input.value = '';
  
  const response = await generateWithGemini(message, true);
  if (response) {
    addChatMessage('tutor', response);
  }
}

